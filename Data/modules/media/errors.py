"""Typed media domain errors — expected operational outcomes, not HTTP 500."""

from __future__ import annotations

MEDIA_WORKER_UNAVAILABLE = "MEDIA_WORKER_UNAVAILABLE"
MEDIA_BACKEND_UNAVAILABLE = "MEDIA_BACKEND_UNAVAILABLE"
MEDIA_FFMPEG_UNAVAILABLE = "MEDIA_FFMPEG_UNAVAILABLE"
MEDIA_FFPROBE_UNAVAILABLE = "MEDIA_FFPROBE_UNAVAILABLE"
MEDIA_INPUT_INVALID = "MEDIA_INPUT_INVALID"
MEDIA_INPUT_TOO_LARGE = "MEDIA_INPUT_TOO_LARGE"
MEDIA_UNSUPPORTED_FORMAT = "MEDIA_UNSUPPORTED_FORMAT"
MEDIA_UNSUPPORTED_CODEC = "MEDIA_UNSUPPORTED_CODEC"
MEDIA_TRANSCODE_FAILED = "MEDIA_TRANSCODE_FAILED"
MEDIA_PROCESSING_FAILED = "MEDIA_PROCESSING_FAILED"
MEDIA_TIMEOUT = "MEDIA_TIMEOUT"
MEDIA_CANCELLED = "MEDIA_CANCELLED"
MEDIA_DISK_FULL = "MEDIA_DISK_FULL"
MEDIA_OUTPUT_INVALID = "MEDIA_OUTPUT_INVALID"
MEDIA_GENERATION_UNAVAILABLE = "MEDIA_GENERATION_UNAVAILABLE"
MEDIA_GENERATION_FAILED = "MEDIA_GENERATION_FAILED"
MEDIA_VISION_UNAVAILABLE = "MEDIA_VISION_UNAVAILABLE"
MEDIA_VISION_FAILED = "MEDIA_VISION_FAILED"
MEDIA_IMAGE_LIMIT_EXCEEDED = "MEDIA_IMAGE_LIMIT_EXCEEDED"
MEDIA_AUDIO_LIMIT_EXCEEDED = "MEDIA_AUDIO_LIMIT_EXCEEDED"
MEDIA_VIDEO_LIMIT_EXCEEDED = "MEDIA_VIDEO_LIMIT_EXCEEDED"
MEDIA_NETWORK_INPUT_BLOCKED = "MEDIA_NETWORK_INPUT_BLOCKED"

MEDIA_ERROR_HTTP_STATUS: dict[str, int] = {
    MEDIA_WORKER_UNAVAILABLE: 503,
    MEDIA_BACKEND_UNAVAILABLE: 503,
    MEDIA_FFMPEG_UNAVAILABLE: 503,
    MEDIA_FFPROBE_UNAVAILABLE: 503,
    MEDIA_INPUT_INVALID: 422,
    MEDIA_INPUT_TOO_LARGE: 413,
    MEDIA_UNSUPPORTED_FORMAT: 422,
    MEDIA_UNSUPPORTED_CODEC: 422,
    MEDIA_TRANSCODE_FAILED: 422,
    MEDIA_PROCESSING_FAILED: 422,
    MEDIA_TIMEOUT: 408,
    MEDIA_CANCELLED: 409,
    MEDIA_DISK_FULL: 507,
    MEDIA_OUTPUT_INVALID: 422,
    MEDIA_GENERATION_UNAVAILABLE: 503,
    MEDIA_GENERATION_FAILED: 422,
    MEDIA_VISION_UNAVAILABLE: 503,
    MEDIA_VISION_FAILED: 422,
    MEDIA_IMAGE_LIMIT_EXCEEDED: 413,
    MEDIA_AUDIO_LIMIT_EXCEEDED: 413,
    MEDIA_VIDEO_LIMIT_EXCEEDED: 413,
    MEDIA_NETWORK_INPUT_BLOCKED: 403,
}


class MediaDomainError(Exception):
    def __init__(self, code: str, message: str = "", *, details: dict | None = None) -> None:
        self.code = str(code)
        self.message = str(message or code)
        self.details = dict(details or {})
        super().__init__(self.message)

    def public_dict(self) -> dict:
        return {
            "error_code": self.code,
            "message": self.message,
            "details": self.details,
            "http_status": MEDIA_ERROR_HTTP_STATUS.get(self.code, 422),
        }

"""Typed browser domain errors — expected operational outcomes, not HTTP 500."""

from __future__ import annotations

BROWSER_WORKER_UNAVAILABLE = "BROWSER_WORKER_UNAVAILABLE"
BROWSER_BACKEND_UNAVAILABLE = "BROWSER_BACKEND_UNAVAILABLE"
BROWSER_CHROMIUM_UNAVAILABLE = "BROWSER_CHROMIUM_UNAVAILABLE"
BROWSER_SESSION_LOST = "BROWSER_SESSION_LOST"
BROWSER_SESSION_EXPIRED = "BROWSER_SESSION_EXPIRED"
BROWSER_NAVIGATION_FAILED = "BROWSER_NAVIGATION_FAILED"
BROWSER_NAVIGATION_TIMEOUT = "BROWSER_NAVIGATION_TIMEOUT"
BROWSER_TARGET_BLOCKED = "BROWSER_TARGET_BLOCKED"
BROWSER_ACTION_FAILED = "BROWSER_ACTION_FAILED"
BROWSER_ACTION_TIMEOUT = "BROWSER_ACTION_TIMEOUT"
BROWSER_DOWNLOAD_FAILED = "BROWSER_DOWNLOAD_FAILED"
BROWSER_UPLOAD_DENIED = "BROWSER_UPLOAD_DENIED"
BROWSER_SCREENSHOT_FAILED = "BROWSER_SCREENSHOT_FAILED"
BROWSER_QA_FAILED = "BROWSER_QA_FAILED"
BROWSER_QA_CANCELLED = "BROWSER_QA_CANCELLED"
BROWSER_QA_LIMIT_REACHED = "BROWSER_QA_LIMIT_REACHED"
BROWSER_QA_RESUME_DIVERGED = "BROWSER_QA_RESUME_DIVERGED"
BROWSER_REPLAY_DIVERGED = "BROWSER_REPLAY_DIVERGED"

BROWSER_ERROR_HTTP_STATUS: dict[str, int] = {
    BROWSER_WORKER_UNAVAILABLE: 503,
    BROWSER_BACKEND_UNAVAILABLE: 503,
    BROWSER_CHROMIUM_UNAVAILABLE: 503,
    BROWSER_SESSION_LOST: 409,
    BROWSER_SESSION_EXPIRED: 410,
    BROWSER_NAVIGATION_FAILED: 422,
    BROWSER_NAVIGATION_TIMEOUT: 408,
    BROWSER_TARGET_BLOCKED: 403,
    BROWSER_ACTION_FAILED: 422,
    BROWSER_ACTION_TIMEOUT: 408,
    BROWSER_DOWNLOAD_FAILED: 422,
    BROWSER_UPLOAD_DENIED: 403,
    BROWSER_SCREENSHOT_FAILED: 422,
    BROWSER_QA_FAILED: 422,
    BROWSER_QA_CANCELLED: 409,
    BROWSER_QA_LIMIT_REACHED: 422,
    BROWSER_QA_RESUME_DIVERGED: 409,
    BROWSER_REPLAY_DIVERGED: 409,
}


class BrowserDomainError(Exception):
    def __init__(self, code: str, message: str = "", *, details: dict | None = None) -> None:
        self.code = str(code)
        self.message = str(message or code)
        self.details = dict(details or {})
        super().__init__(self.message)

    def public_dict(self) -> dict:
        return {
            "error_code": self.code,
            "message": self.message,
            "details": self.details,
            "http_status": BROWSER_ERROR_HTTP_STATUS.get(self.code, 422),
        }

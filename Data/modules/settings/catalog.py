def _b(
    key: str,
    category: str,
    label: str,
    description: str,
    *,
    default: bool,
    env: str,
    path: tuple[str, ...],
    consumer: str,
    requires: tuple[str, ...] = (),
    dangerous: bool = False,
    apply_mode: ApplyMode = ApplyMode.HOT,
    experimental: bool = True,
) -> SettingDefinition:
    return SettingDefinition(
        key=key,
        category=category,
        label=label,
        description=description,
        value_type=SettingType.BOOLEAN,
        default=default,
        env_name=env,
        path=path,
        requires=requires,
        dangerous=dangerous,
        apply_mode=apply_mode,
        consumer=consumer,
        experimental=experimental,
    )


